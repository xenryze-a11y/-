export function regionAt(p: Vec2): RegionId {
  const x = p.x / 32,
    y = p.y / 32;
  if (x < 128 && y < 96)
    return x < 48 && y < 48 ? 'vale' : x >= 48 && y < 64 ? 'sanctum' : 'forest';
  if (x < 96 && y >= 96 && y < 160) return 'vale';
  return x >= 128 && y < 128 ? 'sanctum' : 'forest';
}

