export function roadClearance(x: number, y: number): boolean {
  const xx = x / 32,
    yy = y / 32;
  const old =
    xx < 128 &&
    yy < 96 &&
    ((Math.abs(xx - 24.5) < 1.9 && yy > 47) ||
      (Math.abs(yy - 76.5) < 1.9 && xx > 22) ||
      (Math.abs(xx - 110.5) < 1.9 && yy > 28) ||
      (Math.abs(yy - 30.5) < 1.9 && xx > 69));
  return old || newRoad(xx, yy);
}
