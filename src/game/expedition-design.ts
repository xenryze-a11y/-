/** 平面折线保留朝向变化，路中段用于战斗空地/桥口构图。 */
export function frontierPaths(): number[][][] {
  const pos = (i: number): number[] => [
    FRONTIER_NODES[i][4],
    FRONTIER_NODES[i][5],
  ];
  return [
    ...FRONTIER_LINKS.map(([a, b]) => {
      const p = pos(a),
        q = pos(b);
      return [
        p,
        [(p[0] + q[0]) / 2 + ((a + b) % 2 ? 5 : -5), (p[1] + q[1]) / 2],
        q,
      ];
    }),
    ...FRONTIER_GATEWAYS.map((g) => [g.from, pos(g.to)]),
  ];
}
